#!/usr/bin/env python3
"""Writes the scripts for Fighting Vipers 2's full 3D texture dump.

    tools/scripts/dump-full/00-attract.txt        the boot, the logos, the title
                                                  screen and the demo
    tools/scripts/dump-full/c<NN>-colour<N>.txt   one fight per cursor cell, in
                                                  both of its colours

The port only renders the picture on a script's `shot` marks: the close marks,
one every twelve frames, are not there to make pictures -- the launcher gives no
`--shots` -- but to force the rendering, and so the sampling. What is not drawn
is not captured.

The cursor starts on EMI, cell 0; one press of right per cell. Without the
roster patch the row wraps at cell 10; with `--full-roster` it goes to 14
(docs/fv2-roster.md), and the launcher passes it. Cell 10 is the random draw: it
gives some fighter or other, which does no harm to a capture whose aim is to see
as much as possible go by.

One press of UP on the cell before confirming gives the costume's second colour
(*1P COLOR 0x007005B9 goes from 0 to 1).

Guard is held through the round: armour that falls makes another model load.
Here that is not a flaw -- those textures interest us too -- but holding it makes
the thirty runs comparable with one another.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "scripts", "dump-full"))

CURSOR_MAX = 14          # with --full-roster; 10 without
START, END, STEP = 2400, 4400, 12
ATTRACT_START, ATTRACT_END, ATTRACT_STEP = 60, 1860, 12


def marks(start, end, step, extra=()):
    """The render marks, plus whatever is to be slipped in among them, in order:
    the script reader stops on a frame that goes backwards."""
    seq = [(f, "%d shot t%03d" % (f, i))
           for i, f in enumerate(range(start, end + 1, step))]
    seq += list(extra)
    seq.sort(key=lambda c: c[0])
    return [line for _, line in seq]


def attract():
    L = ["# Fighting Vipers 2: the boot, the logos, the title screen and the demo.",
         "# No input: the attract is watched running and everything that appears",
         "# is captured.",
         "# Generated by tools/fv2/mk_dump_full.py -- do not edit by hand."]
    L += marks(ATTRACT_START, ATTRACT_END, ATTRACT_STEP)
    L.append("%d quit" % (ATTRACT_END + 60))
    return "\r\n".join(L) + "\r\n"


def fight(cursor, colour):
    L = ["# Fighting Vipers 2: cursor cell %d, colour %d." % (cursor, colour),
         "# %d press(es) of right from EMI%s, then punch confirms."
         % (cursor, ", one of UP" if colour == 2 else ""),
         "# Generated by tools/fv2/mk_dump_full.py -- do not edit by hand.",
         "1900 press p1.coin",
         "1930 press p1.coin",
         "1960 press p1.start"]
    # The moments are computed: at fifteen cells, a fixed spacing would put the
    # last press of right after the press of UP, and the script reader stops on
    # a frame that goes backwards.
    t = 2040
    for _ in range(cursor):
        L.append("%d press p1.right" % t)
        t += 16
    if colour == 2:
        t += 30
        L.append("%d press p1.up" % t)
    t += 30
    L.append("%d press p1.punch" % t)
    assert t < START, (cursor, colour, t)
    L += marks(START, END, STEP, extra=[(3150, "3150 hold p1.guard")])
    L.append("%d quit" % (END + 100))
    return "\r\n".join(L) + "\r\n"


os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith(".txt"):
        os.remove(os.path.join(OUT, f))

files = [("00-attract.txt", attract())]
for c in range(CURSOR_MAX + 1):
    for colour in (1, 2):
        files.append(("c%02d-colour%d.txt" % (c, colour), fight(c, colour)))

for name, content in files:
    with open(os.path.join(OUT, name), "wb") as fh:
        fh.write(content.encode("ascii"))
print("%d scripts in %s" % (len(files), OUT))
