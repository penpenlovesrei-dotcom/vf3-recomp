#!/usr/bin/env python3
"""Writes the three input scripts used to isolate Honey's textures.

Three runs, the same in everything but one thing each:

    fv2-honey-tex-c1.txt   HONEY confirmed with PUNCH  -> the first colour
    fv2-honey-tex-c2.txt   HONEY confirmed with START  -> the second colour
    fv2-emi-tex.txt        EMI confirmed with PUNCH    -> the control

The control is the only way to isolate Honey: the capture writes everything a
polygon samples, so the scenery, the sky, the opponent and the effects come with
her. What Honey's run has and the control does not is Honey.

Two precautions taken in the scripts, and they are the heart of the matter:

  * No frame is rendered before the confirmation. The cursor crosses cells 1 to
    8 to reach HONEY, and the select screen draws the model of the cell under
    it: rendering those frames would bring seven other characters' textures
    into the capture, which the control would not have. So the capture only
    begins once the fight is loaded.

  * `hold p1.guard` through the round. Honey's lower armour takes 300 points and
    the upper 350 (docs/fv2-honey.md); once it has fallen, the game loads another
    model and its textures would enter the capture. With guard held, what is
    asked for is the basic costume and nothing else.

The port only renders the picture on a script's `shot` marks: the close marks
below are not there to make pictures -- the launcher gives no `--shots` -- they
are there to force the rendering, and so the sampling.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.normpath(os.path.join(HERE, "..", "scripts"))

# The capture's two bounds. 2400: the fight has been asked for, the select
# screen is behind us. 4400: the first round ends between 4900 and 5100 with
# random play (docs/fv2-honey.md); we stop before that so as never to load the
# next round.
START, END, STEP = 2400, 4400, 12


def run(title, rights, confirm, up=False):
    L = ["# " + l for l in title.splitlines()]
    L += [
        "# Generated by tools/fv2/mk_honey_tex_scripts.py -- do not edit by hand.",
        "1900 press p1.coin",
        "1930 press p1.coin",
        "1960 press p1.start",
    ]
    # The cursor starts on EMI. One press of right per cell, as in
    # fv2-honey.txt, at the same frames so that the three runs are comparable.
    for n in range(rights):
        L.append("%d press p1.right" % (2080 + 30 * n))
    if up:
        # The costume's second colour: one press of UP on the cell, before
        # confirming. Frederic saw it work; START, which a comment in
        # fv2-honey.txt gave as the costume choice, confirms nothing at all --
        # it calls the second player, and the select clock runs out (measured on
        # 2026-10-21).
        L.append("2320 press p1.up")
    L.append("2350 press p1." + confirm)
    L.append("# Render marks, one every %d frames: it is the rendering that" % STEP)
    L.append("# samples the textures, not the picture written. The guard is taken")
    L.append("# in order, the script reader refusing a frame that goes backwards.")
    # vf3run reads the commands in order and stops on a frame that goes
    # backwards: so the guard has to be laid at its place in the sequence.
    seq = [(f, "%d shot t%03d" % (f, i))
           for i, f in enumerate(range(START, END + 1, STEP))]
    seq.append((3150, "3150 hold p1.guard"))
    seq.sort(key=lambda c: c[0])
    L += [line for _, line in seq]
    L.append("%d quit" % (END + 100))
    return "\r\n".join(L) + "\r\n"


FILES = {
    "fv2-honey-tex-c1.txt": run(
        "Fighting Vipers 2: HONEY, the first colour, for the texture capture.\n"
        "Eight presses of right from EMI arrive on HONEY, cell 8; PUNCH confirms,\n"
        "and punch gives the costume in its first colour.",
        8, "punch"),
    "fv2-honey-tex-c2.txt": run(
        "Fighting Vipers 2: HONEY, the second colour, for the texture capture.\n"
        "Strictly run c1, to within one press: UP on HONEY's cell before\n"
        "confirming with punch, and the costume changes colour.",
        8, "punch", up=True),
    "fv2-emi-tex.txt": run(
        "Fighting Vipers 2: EMI, the control for Honey's texture capture.\n"
        "No press of right -- the cursor arrives on EMI -- and PUNCH confirms. The\n"
        "same opening, the same opponent, the same scenery, the same timing as\n"
        "Honey's two runs: so everything this one shares with hers is not Honey.",
        0, "punch"),
}

for name, content in FILES.items():
    path = os.path.join(SCRIPTS, name)
    with open(path, "wb") as f:
        f.write(content.encode("ascii"))
    print("%-24s %d lines" % (name, content.count("\r\n")))
