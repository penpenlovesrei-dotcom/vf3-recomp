#!/usr/bin/env python3
"""The scripts for the "armour blown off" dump: the game's second face.

    mk_dump_armour.py [<number of colours>]

One run per cursor cell and per colour, in tools/scripts/dump-armour/.

Why a second dump. A Fighting Vipers 2 fighter wears armour, and under the
armour there is another model, with textures of its own. The first dump held
guard all round long so that the armour would not fall: so it never saw what is
underneath. Cell 14's chrome is the proof by absurdity -- zero textures of its
own over 240 encounters, because its whole body IS the armour.

How the armour is made to fall. Player 1's `flag0` is at `0x00701444`
(docs/fv2-honey.md); its bits: 0x01 and 0x02 "the piece has reached its limit",
0x04 and 0x08 "the piece has FALLEN". It is 0x04 and 0x08 that the model reads,
not 0x01 and 0x02. So the launcher writes 15 (0x0F) into the low byte, which is
"both pieces at their limit and both fallen".

And the moment counts for more than the value: **the model is chosen when a
round loads**, never during it. Armour torn off mid-round changes nothing in the
picture before that round ends. Hence the shape of these runs:

    3150   random play, so that the round gets played
    3200   the poke begins and never stops
    ~4900  round 1 ends (the clock is enough for that, measured)
    5150   the render marks begin -- it is round 2 that is captured
    7400   the end

Marks before 5150 would be waste: they would show only the intact model, which
the first dump already has.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "scripts", "dump-armour"))

CURSOR_MAX = 14
START, END, STEP = 5150, 7400, 12
SEED = 20261021


def run(cursor, colour):
    L = ["# Cursor cell %d, colour %d, the armour blown off." % (cursor, colour),
         "# The launcher holds VF3_POKE=701444=15 from frame 3200 on; the render",
         "# marks begin only at round 2, where the model is read again.",
         "# Generated by tools/fv2/mk_dump_armour.py -- do not edit by hand.",
         "1900 press p1.coin",
         "1930 press p1.coin",
         "1960 press p1.start"]
    t = 2040
    for _ in range(cursor):
        L.append("%d press p1.right" % t)
        t += 16
    for _ in range(colour - 1):
        t += 24
        L.append("%d press p1.up" % t)
    t += 30
    L.append("%d press p1.punch" % t)
    assert t < 2400, (cursor, colour, t)
    # Random play keeps the round alive; the clock ends it in any case, which
    # makes the run independent of the fighter.
    L.append("3150 random p1 %d" % SEED)
    L += ["%d shot t%03d" % (f, i)
          for i, f in enumerate(range(START, END + 1, STEP))]
    L.append("%d quit" % (END + 100))
    return "\r\n".join(L) + "\r\n"


colours = int(sys.argv[1]) if len(sys.argv) > 1 else 2
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith(".txt"):
        os.remove(os.path.join(OUT, f))

n = 0
for c in range(CURSOR_MAX + 1):
    for k in range(1, colours + 1):
        name = "a%02d-colour%d.txt" % (c, k)
        open(os.path.join(OUT, name), "wb").write(run(c, k).encode("ascii"))
        n += 1
print("%d scripts in %s  (%d colours)" % (n, OUT, colours))
