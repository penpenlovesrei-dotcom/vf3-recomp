#!/usr/bin/env python3
"""How many colours a costume has, and how they are reached.

    mk_colours.py <cursor> [<cursor> ...]

Writes into tools/scripts/colours/ one run per number of presses of UP on the
cell, from 0 to 3, and one per press of DOWN, from 1 to 3. Each one stops just
after frame 3300, where the launcher reads *1P COLOR (0x007005B9).

Why DOWN as well: nothing says the colours are taken in one direction only. If
the row of colours wraps, UP x3 and DOWN x1 give the same one, and it is the
measurement that will say so, not the reasoning.

No render marks: without `shot` the port draws nothing, and all that is wanted
here is the byte.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "scripts", "colours"))


def run(cursor, way, how_many):
    L = ["# Cursor cell %d, %d press(es) of %s before the punch."
         % (cursor, how_many, way.upper()),
         "# Generated by tools/fv2/mk_colours.py -- do not edit by hand.",
         "1900 press p1.coin",
         "1930 press p1.coin",
         "1960 press p1.start"]
    t = 2040
    for _ in range(cursor):
        L.append("%d press p1.right" % t)
        t += 16
    for _ in range(how_many):
        t += 24
        L.append("%d press p1.%s" % (t, way))
    t += 30
    L.append("%d press p1.punch" % t)
    assert t < 2400, (cursor, way, how_many, t)
    L.append("3310 quit")
    return "\r\n".join(L) + "\r\n"


os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith(".txt"):
        os.remove(os.path.join(OUT, f))

n = 0
for cursor in (int(a) for a in sys.argv[1:]):
    for how_many in range(4):
        name = "c%02d-up%d.txt" % (cursor, how_many)
        open(os.path.join(OUT, name), "wb").write(run(cursor, "up", how_many).encode("ascii"))
        n += 1
    for how_many in range(1, 4):
        name = "c%02d-down%d.txt" % (cursor, how_many)
        open(os.path.join(OUT, name), "wb").write(run(cursor, "down", how_many).encode("ascii"))
        n += 1
print("%d scripts in %s" % (n, OUT))
